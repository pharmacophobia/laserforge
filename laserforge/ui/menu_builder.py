        m.addAction(a.duplicate)
        m.addAction(a.delete)
        m.addSeparator()
        m.addAction(a.flip_h)
        m.addAction(a.flip_v)
        m.addSeparator()
        m_bool = m.addMenu("📐 Vector Booleans (CSG)")
        m_bool.addAction(a.weld)
        m_bool.addAction(a.subtract)
        m_bool.addAction(a.intersect)
        m_bool.addAction(a.xor)
        m.addAction(a.weld)
        m.addAction(a.subtract)
        m.addAction(a.intersect)
        m.addAction(a.xor)
        m.addSeparator()
        m.addAction(a.add_to_art_library)
        m.addAction(a.convert_to_path)

