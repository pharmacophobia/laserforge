    def _build_help_menu(self, mb):
        a = self._actions
        m = mb.addMenu('&Help')
        m.addAction(a.user_guide)
        m.addAction(a.interactive_tutorial)
        m.addAction(a.send_feedback)
        m.addSeparator()
        m.addAction(a.license)
        m.addAction(a.check_updates)
        m.addSeparator()
