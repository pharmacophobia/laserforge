class HersheyFont:
    """Single-line stroke font generator for laser marking and engraving."""

    @classmethod
    def render_text(
        cls,
        text: str,
        font_size_mm: float = 10.0,
        x: float = 0.0,
        y: float = 0.0,
        char_spacing: float = 1.0,
        line_spacing: float = 1.4
    ) -> List[List[Tuple[float, float]]]:
        """
        Renders text into a list of open stroke polylines for single-pass laser engraving.

        Parameters:
            text: Text string (can include newlines)
            font_size_mm: Height of capital letters in mm
            x, y: Top-left start position in mm
            char_spacing: Character spacing multiplier
            line_spacing: Line spacing multiplier

        Returns:
            List of stroke paths: [[(x1, y1), (x2, y2), ...], ...]
        """
        if not text:
            return []

        # Hershey grid: Cap height is ~21 units (-12 to +9)
        unit_scale = font_size_mm / 21.0
        line_height_mm = font_size_mm * line_spacing

        strokes: List[List[Tuple[float, float]]] = []

        lines = text.splitlines()
        for row_idx, line in enumerate(lines):
            cur_x = x
            # Baseline y position for this row: cap height at top, baseline at bottom
            baseline_y = y + (row_idx * line_height_mm) + (font_size_mm * (12.0 / 21.0))

            for char in line:
                glyph = _HERSHEY_SIMPLEX_DATA.get(char)
                if glyph is None:
                    # Fallback to uppercase or space
                    glyph = _HERSHEY_SIMPLEX_DATA.get(char.upper(), _HERSHEY_SIMPLEX_DATA.get(" ", (10.0, [])))

                adv_w, g_strokes = glyph
                for s in g_strokes:
                    world_stroke = []
                    for sx, sy in s:
                        wx = cur_x + (sx * unit_scale)
                        wy = baseline_y + (sy * unit_scale)
                        world_stroke.append((wx, wy))
                    if len(world_stroke) >= 2:
                        strokes.append(world_stroke)

                cur_x += (adv_w * unit_scale) * char_spacing

        return strokes

    @classmethod
    def create_entity(
        cls,
        text: str,
        x: float = 0.0,
        y: float = 0.0,
        font_size_mm: float = 10.0,
        layer_id: int = 0,
        name: str = "SingleLineText"
    ) -> Optional[PathEntity]:
        """Creates a PathEntity with closed=False containing single-line strokes."""
        strokes = cls.render_text(text, font_size_mm=font_size_mm, x=x, y=y)
        if not strokes:
            return None

        # Convert absolute world strokes into relative to (x, y)
        rel_contours = []
        for s in strokes:
            rel_contours.append([(px - x, py - y) for px, py in s])

        return PathEntity(
            layer_id=layer_id,
            name=name,
            x=x,
            y=y,
            contours=rel_contours,
            closed=False  # Crucial: open strokes!
        )
